package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
)

const module = "smarthub"

func main() {
	entries, err := os.ReadDir("../../plugins")
	if err != nil {
		panic(err)
	}
	var imports []string
	for _, e := range entries {
		if e.IsDir() {
			imports = append(imports, fmt.Sprintf("\t_ %q", module+"/plugins/"+e.Name()))
		}
	}
	sort.Strings(imports)

	var b strings.Builder
	b.WriteString("// Code generated by tools/genplugins. DO NOT EDIT.\n\npackage main\n\nimport (\n")
	for _, imp := range imports {
		b.WriteString(imp + "\n")
	}
	b.WriteString(")\n")

	if err := os.WriteFile("plugins_gen.go", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("registered %d plugin packages\n", len(imports))
}
